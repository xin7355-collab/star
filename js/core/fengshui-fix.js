/** 依使用者的喜用五行補一句「植物怎麼挑」，沒有喜用（資料不足）就不補 */
export function tailor(issue, ys) {
  if (!issue.plant || !ys || !PLANT_NOTE[ys.primary]) return '';
  return PLANT_NOTE[ys.primary];
}

/** 依勾選的 id 取出要顯示的化解（保持清單順序、忽略不認得的 id） */
export function pickIssues(ids) {
  const set = new Set(Array.isArray(ids) ? ids : []);
  return ISSUES.filter((x) => set.has(x.id));
}

