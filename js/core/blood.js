export function isBloodType(v) {
  return BLOOD_TYPES.includes(v);
}

/** 兩種血型的相處說明；任一方沒填就回傳 null */
export function bloodMatch(a, b) {
  if (!isBloodType(a) || !isBloodType(b)) return null;
  const key = [a, b].sort().join('-');
  return { pair: `${a} 型 × ${b} 型`, text: PAIR_TEXT[key] };
}
