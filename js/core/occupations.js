/** 大類 → 中類 → 細類（「從類別挑」用）：[{ code, name, subs: [{ code, name, units: [{ code, name }] }] }] */
export const SOC_TREE = (() => {
  const majors = [];
  for (const [code, name] of SOC_NAMES) {
    if (code.length === 1) majors.push({ code, name, subs: [] });
    else if (code.length === 2) majors[majors.length - 1].subs.push({ code, name, units: [] });
    else if (code.length === 4) {
      const subs = majors[majors.length - 1].subs;
      subs[subs.length - 1].units.push({ code, name });
    }
  }
  return majors;
})();

