const STAGE_NUM = { 苦: -1, 平: 0, 順: 1 };
/** 早、中、晚三段 → 類型 */
export function patternOf(total) {
  const st = STAGES[total];
  if (!st) return null;
  const [e, m, l] = [...st].map((c) => STAGE_NUM[c]);
  // 先看晚年有沒有比早年好（「老來稍可免憂愁」這種先苦後穩的，不算辛苦型），再看整體是不是很辛苦
  let key = 'flat';
  if (e + m + l === 3) key = 'steady';
  else if (l > e) key = l === 1 ? (m === 1 ? 'midrise' : 'late') : 'selfmade';
  else if (e + m + l <= -2) key = 'hard';
  else if (e > l) key = 'early';
  return { key, ...PATTERNS[key], stages: [...st] };
}

/** 骨重區間：古書的說法＋現代看法（輕不等於壞、重不等於好） */
