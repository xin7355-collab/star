/** 時（0–23）→ 時辰序號（23 點與 0 點都是子時） */
export function shichenIndex(h) {
  return Math.floor(((h + 1) % 24) / 2);
}

/** 骨重顯示：42 → 4 兩 2 錢 */
export function formatWeight(qian) {
  const liang = Math.floor(qian / 10);
  const rest = qian % 10;
  if (!liang) return `${rest} 錢`;
  return rest ? `${liang} 兩 ${rest} 錢` : `${liang} 兩`;
}

/**
 * @param {{yearGanZhi:string, lunarMonth:number, lunarDay:number, hour:number}} input
 */
export function chengGu({ yearGanZhi, lunarMonth, lunarDay, hour }) {
  const parts = {
    year: YEAR_WEIGHT[yearGanZhi],
    month: MONTH_WEIGHT[lunarMonth],
    day: DAY_WEIGHT[lunarDay],
    hour: HOUR_WEIGHT[shichenIndex(hour)],
  };
  if (Object.values(parts).some((v) => !v)) return { ok: false, error: '資料不完整，無法稱骨' };
  const total = parts.year + parts.month + parts.day + parts.hour;
  return {
    ok: true,
    parts,
    total,
    shichen: SHICHEN[shichenIndex(hour)],
    text: formatWeight(total),
    poem: POEMS[total] || '此骨重不在常見歌訣範圍內。',
  };
}
